<script setup>
import { computed } from 'vue'

const props = defineProps({
  name: { type: String, required: true },
  size: { type: Number, default: 48 },
  color: { type: String, default: '#2DD4BF' },
})

// Emoji icons: native emoji rendered to PNG.  color prop is ignored.
const EMOJI_ICONS = new Set([
  'home', 'hospital', 'stethoscope', 'virus', 'pill', 'pill2', 'store', 'robot',
  'heart', 'file', 'message', 'news', 'calendar', 'folder', 'user', 'settings',
  'search', 'pin', 'location', 'phone', 'clock', 'edit', 'lock', 'logout',
  'refresh', 'shield', 'clipboard', 'activity', 'send', 'map', 'star', 'eye',
  'book', 'brain', 'pulse', 'flask',
])

// Symbol icons: rendered in specific colors to PNG.
const SYMBOL_ICONS = new Set([
  'chevronRight', 'chevronLeft', 'back', 'check', 'checkCircle', 'close',
  'plus', 'dot', 'arrowUp', 'arrowDown',
])

// Color palette generated by scripts/gen_icons.py
const PALETTE = {
  '#ffffff': 'ffffff',
  '#c7c7cc': 'c7c7cc',
  '#2dd4bf': '2dd4bf',
  '#7fdbff': '7fdbff',
  '#ff9500': 'ff9500',
  '#34c759': '34c759',
  '#ff3b30': 'ff3b30',
  '#af52de': 'af52de',
  '#8e8e93': '8e8e93',
  '#bbbbbb': 'bbbbbb',
}

function hexToRgb(hex) {
  const h = hex.replace('#', '')
  return {
    r: parseInt(h.substring(0, 2), 16),
    g: parseInt(h.substring(2, 4), 16),
    b: parseInt(h.substring(4, 6), 16),
  }
}

function colorDistance(c1, c2) {
  const rgb1 = hexToRgb(c1)
  const rgb2 = hexToRgb(c2)
  return Math.sqrt(
    Math.pow(rgb1.r - rgb2.r, 2) +
    Math.pow(rgb1.g - rgb2.g, 2) +
    Math.pow(rgb1.b - rgb2.b, 2),
  )
}

function normalizeColor(color) {
  if (!color) return '#2DD4BF'
  const c = color.trim().toLowerCase()

  // rgba/rgb -> hex (drop alpha)
  if (c.startsWith('rgba')) {
    const parts = c.replace(/rgba\(|\)|\s/g, '').split(',')
    if (parts.length >= 3) {
      const r = parseInt(parts[0], 10)
      const g = parseInt(parts[1], 10)
      const b = parseInt(parts[2], 10)
      return `#${r.toString(16).padStart(2, '0')}${g.toString(16).padStart(2, '0')}${b.toString(16).padStart(2, '0')}`
    }
  }
  if (c.startsWith('rgb')) {
    const parts = c.replace(/rgb\(|\)|\s/g, '').split(',')
    if (parts.length >= 3) {
      const r = parseInt(parts[0], 10)
      const g = parseInt(parts[1], 10)
      const b = parseInt(parts[2], 10)
      return `#${r.toString(16).padStart(2, '0')}${g.toString(16).padStart(2, '0')}${b.toString(16).padStart(2, '0')}`
    }
  }

  if (!c.startsWith('#')) {
    return c // fallback
  }

  let h = c.slice(1)
  if (h.length === 3) {
    h = h.split('').map(ch => ch + ch).join('')
  }
  if (h.length === 4) {
    h = h.slice(0, 3).split('').map(ch => ch + ch).join('')
  }
  return `#${h.slice(0, 6)}`
}

function findNearestColor(color) {
  const normalized = normalizeColor(color)

  // Exact match (case-insensitive)
  const lower = normalized.toLowerCase()
  if (PALETTE[lower]) return PALETTE[lower]

  // Find closest by RGB distance
  let best = 'ffffff'
  let minDist = Infinity
  for (const paletteHex of Object.keys(PALETTE)) {
    const dist = colorDistance(lower, paletteHex)
    if (dist < minDist) {
      minDist = dist
      best = PALETTE[paletteHex]
    }
  }
  return best
}

const src = computed(() => {
  if (EMOJI_ICONS.has(props.name)) {
    return `/static/icons/${props.name}.png`
  }
  if (SYMBOL_ICONS.has(props.name)) {
    const suffix = findNearestColor(props.color)
    return `/static/icons/${props.name}_${suffix}.png`
  }
  // Unknown name: fallback to dot
  return `/static/icons/dot_ffffff.png`
})

const style = computed(() => ({
  width: props.size + 'rpx',
  height: props.size + 'rpx',
}))
</script>

<template>
  <image class="ui-icon" :src="src" :style="style" mode="aspectFit" />
</template>

<style scoped>
.ui-icon {
  display: inline-block;
  vertical-align: middle;
}
</style>
